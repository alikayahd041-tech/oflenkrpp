create table if not exists profiles (
  id bigint generated by default as identity primary key,
  email text unique not null,
  name text,
  avatar_url text,
  created_at timestamptz default now()
);

create table if not exists user_roles (
  user_id bigint primary key references profiles(id) on delete cascade,
  role text not null,
  created_at timestamptz default now()
);

create table if not exists rules (
  id bigint generated by default as identity primary key,
  server text not null check (server in ('tr','ksa')),
  category text not null,
  title text not null,
  body text not null,
  sort_order int default 0,
  author_id bigint references profiles(id),
  created_at timestamptz default now()
);

create table if not exists complaints (
  id bigint generated by default as identity primary key,
  server text not null check (server in ('tr','ksa')),
  kind text not null check (kind in ('player','admin')),
  crime text not null,
  reported_name text not null,
  nickname text not null,
  static_id text not null,
  admin_nickname text,
  date_text text not null,
  time_text text not null,
  proof text,
  status text default 'Beklemede',
  decision_note text,
  submitted_by bigint references profiles(id),
  reviewed_by bigint references profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz default now()
);

create table if not exists applications (
  id bigint generated by default as identity primary key,
  server text not null check (server in ('tr','ksa')),
  kind text not null check (kind in ('leader','manager','assistant')),
  answers jsonb not null,
  status text default 'Beklemede',
  decision_note text,
  submitted_by bigint references profiles(id),
  reviewed_by bigint references profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz default now()
);

create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id bigint references profiles(id) on delete cascade,
  server text,
  message text not null,
  link text,
  read boolean default false,
  created_at timestamptz default now()
);

create table if not exists companies (
  id bigint generated by default as identity primary key,
  server text not null check (server in ('tr','ksa')),
  name text not null,
  description text,
  created_at timestamptz default now()
);

create table if not exists audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint references profiles(id),
  action text not null,
  target_id text,
  details jsonb,
  created_at timestamptz default now()
);

